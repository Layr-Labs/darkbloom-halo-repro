//! Trusted-local calibration of an offline UKI boot capture.
//!
//! The AK pin and reviewed manifest are trusted inputs, obtained separately
//! from the untrusted capture. This does not replace the coordinator's EK
//! chain verification and EK/AK credential activation, and cannot establish
//! that an arbitrary, newly supplied AK belongs to a hardware TPM.

use base64::Engine as _;
use db_release::Manifest;
use db_tpmattest::{UKI_PCRS, eventlog, parse_attestation_key, pcr_digest, verify_quote};
use serde::Deserialize;
use serde::de::{Error as _, MapAccess, Visitor};
use std::collections::BTreeMap;

/// Maximum serialized capture size (including the base64 event log).
pub const MAX_CAPTURE_BYTES: usize = 4 << 20;
const SEALED_WIFI_PCRS: [u32; 6] = [4, 7, 9, 11, 12, 14];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Capture {
    quoted_pcrs: Vec<u32>,
    ak_public: String,
    attest: String,
    signature: String,
    #[serde(deserialize_with = "unique_pcr_values")]
    pcr_read_sha256: BTreeMap<String, String>,
    event_log: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PinnedAk {
    ak_public: String,
}

// Declare fields in lexical order so output remains canonical even if a
// future dependency enables serde_json's preserve_order feature.
#[derive(serde::Serialize)]
struct PcrReference<'a> {
    bank: &'a str,
    install_id: &'a str,
    pcrs: BTreeMap<String, String>,
    v: u8,
}

// A duplicate PCR key must fail, rather than silently replacing the first
// value. Decimal spelling is checked separately against the exact PCR set.
fn unique_pcr_values<'de, D: serde::Deserializer<'de>>(deserializer: D) -> Result<BTreeMap<String, String>, D::Error> {
    struct Unique;
    impl<'de> Visitor<'de> for Unique {
        type Value = BTreeMap<String, String>;
        fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.write_str("a map of unique decimal PCR indices to SHA-256 hex")
        }
        fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
            let mut out = BTreeMap::new();
            while let Some((key, value)) = map.next_entry::<String, String>()? {
                if out.insert(key, value).is_some() {
                    return Err(A::Error::custom("duplicate PCR index"));
                }
            }
            Ok(out)
        }
    }
    deserializer.deserialize_map(Unique)
}

fn decode_hex(value: &str, what: &str) -> Result<Vec<u8>, String> {
    hex::decode(value).map_err(|e| format!("{what}: {e}"))
}

/// Verify a nonce-bound restricted-AK quote, every selected PCR against the
/// SHA-256 event-log replay, and all reviewed UKI/platform pins. Return only
/// the canonical wizard expected-pcrs.json bytes (sorted keys and newline).
///
/// `release_id` names the installed image, not Manifest::id(). Both it and
/// the reviewed manifest must be chosen by the trusted operator. This step
/// does not authorize serving or authenticate an EK certificate chain.
pub fn verify(capture_raw: &[u8], pinned_raw: &[u8], nonce: &[u8], manifest: &Manifest, release_id: &str) -> Result<Vec<u8>, String> {
    if capture_raw.is_empty() || capture_raw.len() > MAX_CAPTURE_BYTES || pinned_raw.len() > 4096 {
        return Err("calibration input exceeds its size limit or is empty".to_owned());
    }
    if !(16..=32).contains(&nonce.len()) {
        return Err("nonce must be 16-32 fresh verifier-generated bytes".to_owned());
    }
    if release_id.is_empty()
        || release_id.len() > 80
        || !release_id.bytes().next().is_some_and(|b| b.is_ascii_alphanumeric())
        || !release_id.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
    {
        return Err("release-id must be an explicit valid installed release identifier".to_owned());
    }
    if manifest.boot.path != "uki" {
        return Err("calibration requires an independently reviewed UKI manifest".to_owned());
    }
    manifest.validate().map_err(|e| format!("reviewed manifest: {e}"))?;
    let boot = &manifest.boot;
    let reviewed = BTreeMap::from([
        (0, &boot.pcr0_sha256),
        (4, &boot.pcr4_sha256),
        (7, &boot.pcr7_sha256),
        (9, &boot.pcr9_sha256),
        (11, &boot.pcr11_sha256),
        (12, &boot.pcr12_sha256),
        (14, &boot.pcr14_sha256),
    ]);
    for (&pcr, digest) in &reviewed {
        if !db_release::is_sha256_hex(digest) {
            return Err(format!("reviewed manifest must independently pin PCR {pcr}"));
        }
    }

    let capture: Capture = serde_json::from_slice(capture_raw).map_err(|e| format!("quote capture: {e}"))?;
    let pinned: PinnedAk = serde_json::from_slice(pinned_raw).map_err(|e| format!("pinned factory AK: {e}"))?;
    let public = decode_hex(&capture.ak_public, "capture AK")?;
    if public != decode_hex(&pinned.ak_public, "pinned factory AK")? {
        return Err("capture AK does not match the separately pinned trusted factory AK".to_owned());
    }
    let ak = parse_attestation_key(&public).map_err(|e| format!("pinned AK: {e}"))?;
    let mut exact_template = db_tpm2::ak_template();
    exact_template.unique = ak.public.unique.clone();
    if ak.public != exact_template {
        return Err("pinned AK does not use the deterministic restricted CreatePrimary AK template".to_owned());
    }
    let quote = verify_quote(&ak, &decode_hex(&capture.attest, "attestation")?, &decode_hex(&capture.signature, "signature")?, nonce)
        .map_err(|e| format!("quote verification: {e}"))?;
    if quote.bank != eventlog::ALG_SHA256 || quote.pcrs != UKI_PCRS || capture.quoted_pcrs != UKI_PCRS {
        return Err("quote and capture must select exactly the full UKI SHA-256 PCR set including PCR 11".to_owned());
    }
    let expected_keys: std::collections::BTreeSet<String> = UKI_PCRS.iter().map(u32::to_string).collect();
    if capture.pcr_read_sha256.keys().cloned().collect::<std::collections::BTreeSet<_>>() != expected_keys {
        return Err("PCR_Read must contain exactly the canonical full UKI PCR indices".to_owned());
    }
    let mut values = BTreeMap::new();
    for pcr in UKI_PCRS {
        let value = capture.pcr_read_sha256.get(&pcr.to_string()).ok_or_else(|| format!("PCR_Read is missing PCR {pcr}"))?;
        if !db_release::is_sha256_hex(value) {
            return Err(format!("PCR_Read PCR {pcr} must be SHA-256 hex"));
        }
        values.insert(pcr, decode_hex(value, "PCR_Read value")?);
    }
    if pcr_digest(&values, &UKI_PCRS).map_err(|e| e.to_string())? != quote.pcr_digest {
        return Err("PCR_Read values do not match the signed quoted PCR digest".to_owned());
    }
    let log_raw = base64::engine::general_purpose::STANDARD.decode(&capture.event_log).map_err(|e| format!("event log base64: {e}"))?;
    let log = eventlog::parse_event_log(&log_raw).map_err(|e| format!("event log: {e}"))?;
    let replay = log.replay(eventlog::ALG_SHA256, &UKI_PCRS).map_err(|e| format!("SHA-256 replay: {e}"))?;
    if replay != values || pcr_digest(&replay, &UKI_PCRS).map_err(|e| e.to_string())? != quote.pcr_digest {
        return Err("full SHA-256 event-log replay does not match the quoted PCR digest and PCR_Read values".to_owned());
    }
    for (&pcr, expected) in &reviewed {
        if replay.get(&pcr).map(hex::encode).as_deref() != Some(expected.to_ascii_lowercase().as_str()) {
            return Err(format!("quoted PCR {pcr} differs from the independently reviewed manifest"));
        }
    }
    let pcrs: BTreeMap<String, String> = SEALED_WIFI_PCRS
        .iter()
        .map(|pcr| replay.get(pcr).map(|value| (pcr.to_string(), hex::encode(value))).ok_or_else(|| format!("missing PCR {pcr}")))
        .collect::<Result<_, _>>()?;
    // Struct fields and PCR keys are sorted; all values are ASCII. This
    // matches the wizard's json.dumps(sort_keys=True,ensure_ascii=True).
    let output = PcrReference { bank: "sha256", install_id: release_id, pcrs, v: 1 };
    let mut canonical = serde_json::to_vec(&output).map_err(|e| format!("expected PCR JSON: {e}"))?;
    canonical.push(b'\n');
    Ok(canonical)
}
